import type { Metadata, Viewport } from 'next'
import { Geist, Geist_Mono } from 'next/font/google'

import './globals.css'

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
})

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
})

export const metadata: Metadata = {
  title: { default: 'songs', template: '%s · songs' },
  description: 'Testi e accordi, con trasposizione, notazione e scorrimento automatico.',
  applicationName: 'songs',
  /**
   * Declared rather than left to convention.
   *
   * `/favicon.ico` and `/apple-touch-icon.png` would be found by guesswork anyway,
   * but only the tags say which size is which — and iOS picks the touch icon from
   * the tag first. The files are generated by `npm run icons`; every one of them is
   * named `icon-*` or `apple-touch-icon` so the middleware serves it without a
   * session, which is what lets the install prompt show an icon on a locked app.
   */
  icons: {
    icon: [
      { url: '/icon-32.png', type: 'image/png', sizes: '32x32' },
      { url: '/icon-192.png', type: 'image/png', sizes: '192x192' },
    ],
    apple: [{ url: '/apple-touch-icon.png', sizes: '180x180' }],
  },
}

export const viewport: Viewport = {
  // No maximumScale or user-scalable: pinch zoom is an accessibility escape
  // hatch and the font stepper is not a substitute for it.
  width: 'device-width',
  initialScale: 1,
  themeColor: [
    { media: '(prefers-color-scheme: light)', color: '#f6f5f2' },
    { media: '(prefers-color-scheme: dark)', color: '#101216' },
  ],
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  return (
    <html lang="it">
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>{children}</body>
    </html>
  )
}
